#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int	r;
	int	i;
	int	sign;

	r = 0;
	i = 0;
	sign = 1;
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == ' ')
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	while (ft_isdigit(nptr[i]))
	{
		r = r * 10 + (nptr[i] - '0');
		i++;
	}
	return (sign * r);
}
